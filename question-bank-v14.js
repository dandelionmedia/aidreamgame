export function validateExtraQuestions(){
 if(EXTRA_QUESTIONS.length!==15)throw Error('Extra questions require 15 chapters');
 for(let i=0;i<15;i++){
  if(EXTRA_QUESTIONS[i].length!==7)throw Error('Need 7 additional questions in chapter '+(i+1));
  for(const q of EXTRA_QUESTIONS[i])if(q.length!==5||q[2].length!==2||![0,1].includes(q[3]))throw Error('Invalid question');
 }
 return true;
}
