const rewritePairs=[
 [/프롬프트/g,'AI에게 보내는 요청문'],[/서지 정보/g,'책 제목과 지은이 정보'],[/데이터 편향/g,'한쪽으로 치우친 학습 자료'],[/이미지 분석/g,'사진 살펴보기'],[/컴퓨터 비전/g,'사진을 알아보는 AI 기술'],[/음성 인식/g,'말소리를 알아듣는 기술'],[/생성형 AI/g,'글이나 그림을 만드는 AI'],[/표본/g,'조사에 참여한 사람들'],[/대표성/g,'다른 사람들의 의견까지 고루 담았는지'],[/출력 형식/g,'답을 보여주는 모양'],[/라이선스/g,'사용 허락 조건'],[/맥락/g,'그 일이 일어난 상황'],[/확률/g,'일어날 가능성'],[/기압/g,'공기가 누르는 힘'],[/라벨/g,'이름표'],[/근거/g,'믿을 수 있는 이유'],[/검증/g,'확인'],[/편향/g,'한쪽으로 치우침'],[/교과서에서 확인/g,'과학책에서 확인']
];
export function easyText(input){
 let s=String(input||'').trim();
 for(const [from,to] of rewritePairs)s=s.replace(from,to);
 return s;
}
function reasonForWrong(q){
 const correct=q[2][q[3]],wrong=q[2][1-q[3]];
 return '“'+easyText(wrong)+'”는 이 상황에 알맞지 않은 선택이에요. '+easyText(q[4])+' 그래서 “'+easyText(correct)+'”를 선택하는 것이 맞아요. 답을 외우기보다 왜 그런지 생각해 보세요.';
}
export function getQuestionGuide(chapter,index,question){
 const intro=LESSON_INTROS[chapter],scene=SCENES[chapter][index],right=easyText(question[2][question[3]]),wrong=easyText(question[2][1-question[3]]),why=easyText(question[4]);
 return {
  title:easyText(question[1]),
  question:easyText(question[1]),
  illustration:scene,
  intro:intro[1],
  key:intro[2],
  hint:'생각 힌트: '+(index%3===0?'내가 학교에서 같은 일을 겪는다면 어떻게 할까요?':index%3===1?'어느 선택이 더 안전하거나 도움이 될까요?':'친구에게 이유를 설명할 수 있는 선택은 무엇일까요?'),
  correct:'정답은 “'+right+'”예요. '+why,
  wrong:reasonForWrong(question),
  contrast:'다른 선택지 “'+wrong+'”는 이 상황에 어울리지 않아요. '+why,
  tryThis:['우리 반 친구에게 한 문장으로 설명해 보세요.','비슷한 경험이 있었는지 떠올려 보세요.','다음에 실제로 이런 일을 만나면 어떻게 행동할지 말해 보세요.'][index%3],
  glossary:intro[0]
 };
}
export function verifyGuides(courses){
 if(LESSON_INTROS.length!==15||SCENES.length!==15||SIMPLE.length!==15)throw Error('Guide chapter mismatch');
 for(let i=0;i<15;i++){
  if(SCENES[i].length!==10)throw Error('Missing scene in chapter '+i);
  for(let j=0;j<10;j++){
   const g=getQuestionGuide(i,j,courses[i].q[j]);
   if(!g.question||!g.correct||!g.wrong||!g.illustration||!g.hint)throw Error('Missing guide '+i+':'+j);
  }
 }
 return true;
}
